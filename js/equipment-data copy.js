  function collectCatalog(items) {
    if (!items) return;
    for (var i = 0; i < items.length; i++) {
      var it = items[i];
      if (!it || !it.name) continue;
      
      var g = it.group || detectGroup(it.name);
      
      // Исключаем оснащение автомобиля из каталога средств
      if (g === "vehicle") continue;
      
      // Нормализованный ключ для проверки дубликатов
      var normKey = catalogKey(it.name);
      
      if (!catalogMap[normKey]) {
        catalogMap[normKey] = {
          id: it.name,
          name: it.name,
          group: g
        };
      }
    }
  }

