(function () {
  "use strict";

  // =====================================================
  // База инструкций лекарственных средств.
  // Сейчас база пуста — инструкции готовятся к загрузке.
  //
  // Чтобы добавить новый препарат, добавьте блок в объект DRUGS:
  //
  //   "drug-id": {
  //     title: "Название препарата (с дозировкой)",
  //     specialist: `# Markdown для специалиста...`,
  //     patient: `# Markdown для пациента...`  // или "" если одинаково
  //   }
  //
  // - drug-id: совпадает с параметром URL (drug.html?id=drug-id)
  // - specialist: Markdown-текст для специалиста
  // - patient: Markdown-текст для пациента (если пустой — показывается только specialist)
  // =====================================================

  var DRUGS = {};

  // Экспортируем список препаратов
  window.SMP = window.SMP || {};
  window.SMP.drugs = {
    list: DRUGS,
    get: function (id) { return DRUGS[id] || null; }
  };
})();